"""Turn settings into the configuration files Rime and Fcitx5 read.

Files are rendered whole. Nothing here reads an existing file and edits part of
it: a partial write leaves Rime with a schema that silently stops loading, and
whole rendering makes a repeat deploy a no-op instead of a merge.

Two frontends, two owners. Rime's own keys - the schema list, the page size, the
patches per schema - go in the customization files `render` produces. But the
candidate window is drawn by Fcitx5's classicui addon, and the keys classicui
owns are not Rime keys and do not live in Rime's files; `render_fcitx5` produces
those. Getting that split wrong is not a cosmetic mistake: it is a setting wired
to a key nothing reads, which looks exactly like a setting that works until
someone changes it (see `render_fcitx5`).
"""
from __future__ import annotations

import configparser
import io
import re
from pathlib import Path

from lib import assets, settings as settings_lib

HEADER = (
    "# This file is generated by ryuhzk.ime. Edits are lost on the next deploy.\n"
    "# Change the plugin's settings instead.\n"
)

# The two Japanese schemas bracket the Chinese ones: the mixed schema first,
# because it is the one reached by default, and the Japanese-only schema last.
# That is the order the previous dotfiles setup produced and the one the user
# has been typing in, so selecting either keeps its own end of the list.
JAPANESE_HEAD = "japanese_tw_eng"
JAPANESE_TAIL = "sno_japanese"

# The schemas the annotation patches are written for: every Chinese schema in
# the catalogue, because every one of them composes Chinese and a Chinese-English
# gloss on a Chinese candidate is a gloss of that candidate.
#
# Rime reads `<schema_id>.custom.yaml` and nothing else, so this has to be one
# file per selected schema. Writing them all into rime_ice.custom.yaml - which is
# what this did while rime_ice was the only schema that could be selected - hands
# Rime a file it never opens as soon as anything else is picked.
#
# The Japanese two are not here, and that is a decision rather than an omission.
# Their candidates are Japanese, and a CC-CEDICT entry for a kanji string is the
# Chinese word that shares its characters, not a translation of the Japanese one.
# Both schemas also already fill the candidate comment themselves - japanese_tw_eng
# with `simplifier@jpzh_translate_suggestion` (`show_in_comment: true`) and its
# reverse-lookup filters, sno_japanese with the romaji reading - so the filter
# would be fighting over the one slot it writes to.
ANNOTATED_SCHEMAS = frozenset(settings_lib.CHINESE_SCHEMAS)

# The schemas that ship with rime-ice. Each one mounts `simplifier@traditionalize`
# (reading a `traditionalize:` node); no other schema in the catalogue has that
# component - checked against every *.schema.yaml in /usr/share/rime-data.
#
# That matters because a patch key is not a request Rime can refuse. Writing
# `traditionalize/opencc_config` into a schema with no traditionalize component
# builds without complaint and does nothing, which is the same silent no-op this
# change exists to remove - only harder to see, because the file is now there.
# The other Chinese schemas convert through a plain `simplifier` bound to their
# own `simplification` switch, whose meaning is the opposite one; pointing that at
# s2twp would turn "simplify" into "traditionalize" behind the user's back.
RIME_ICE_FAMILY = frozenset({
    "rime_ice", "double_pinyin", "double_pinyin_flypy", "double_pinyin_mspy",
    "double_pinyin_sogou", "double_pinyin_jiajia", "double_pinyin_ziguang",
    "double_pinyin_abc",
})
TRADITIONALIZE_SCHEMAS = RIME_ICE_FAMILY


def _schema_list(settings: dict) -> list[str]:
    """The schema_list this selection produces, in the order Rime reads it.

    Unknown ids are dropped and a selection with no Chinese schema gains the
    default one back. Both repairs happen in lib/settings.resolve as well, and
    are repeated here because rendering must never be the step that produces an
    unbuildable schema_list: an id Rime cannot build fails the whole config, and
    an empty list leaves Rime with nothing to compose with. Whoever asked for
    that on purpose was already refused by settings.validate.
    """
    selected = settings_lib.schema_selection(settings.get("schemas"))
    middle = [
        schema for schema in selected if schema not in (JAPANESE_HEAD, JAPANESE_TAIL)
    ]
    head = [JAPANESE_HEAD] if JAPANESE_HEAD in selected else []
    tail = [JAPANESE_TAIL] if JAPANESE_TAIL in selected else []
    return head + middle + tail


def _default_custom(settings: dict) -> str:
    lines = [
        HEADER,
        "patch:",
        "  __include: rime_ice_suggestion:/",
        "  __patch:",
        "    schema_list:",
    ]
    for schema in _schema_list(settings):
        lines.append(f"      - {{ schema: {schema} }}")
    lines.append(f"    menu/page_size: {settings['pageSize']}")
    # Kept, and no longer the whole story. `style/horizontal` is the Rime key
    # for this, and it is the right key for the Rime frontends that read it -
    # Squirrel on macOS, Weasel on Windows. Under Fcitx5 it reaches nothing:
    # classicui draws the candidate window and takes its own answer from
    # `Vertical Candidate List` (see `render_fcitx5`). Writing both costs a line
    # and keeps the configuration correct wherever it is read.
    lines.append(
        f"    style/horizontal: {'false' if settings['verticalCandidates'] else 'true'}"
    )
    if settings["traditionalize"]:
        lines.append('    "traditionalize/opencc_config": s2twp.json')
    return "\n".join(lines) + "\n"


def _quote(value: str) -> str:
    """YAML double-quoted scalar: a value the user supplied is data, not syntax.

    Every value that reaches a generated file through this is a value someone
    typed - a path into a text field, a hotkey into another - and
    `settings.validate` judges what a hotkey means, not what it does to YAML.
    A bare `"` closes the scalar early and takes the whole schema's build down
    with it; a newline opens a patch key of its own. Both are escaped here so
    that neither can be spelled.
    """
    escaped = (
        str(value)
        .replace("\\", "\\\\")
        .replace('"', '\\"')
        .replace("\n", "\\n")
        .replace("\r", "\\r")
        .replace("\t", "\\t")
    )
    return f'"{escaped}"'


def _schema_custom(settings: dict, schema: str, dictionary_path: str) -> str | None:
    """The `<schema>.custom.yaml` body for one schema, or None if it needs none.

    Every key here is written only into a schema that has the component reading
    it. A patch Rime applies to a node nothing consumes is indistinguishable
    from a patch that never arrived, which is the failure this file exists to
    avoid rather than to relocate.

    None rather than an empty `patch:` when nothing applies: Rime is happy with
    an empty patch, but a file in the manifest that says nothing still has to be
    carried and uninstalled, and returning None means turning a setting off
    removes the file instead of blanking it.
    """
    annotating = (
        schema in ANNOTATED_SCHEMAS
        and (settings["annotateChinese"] or settings["annotateEnglish"])
    )
    lines = [HEADER, "patch:"]
    before = len(lines)
    if settings["traditionalize"] and schema in TRADITIONALIZE_SCHEMAS:
        lines.append("  traditionalize/opencc_config: s2twp.json")
    if annotating:
        lines.append('  "engine/filters/+":')
        lines.append('    - "lua_filter@*annotate"')
        # One switch, not one per direction. Rime's key_binder applies the first
        # binding that matches and stops, so two bindings on the same key would
        # leave the second one dead - and dead in the quiet way, where the key
        # appears to work because the other direction still toggles.
        #
        # The split that does work: the hotkey answers "show glosses right now",
        # which is worth reaching for mid-word, and which direction to gloss is a
        # setting, because nobody changes their mind about that while typing.
        #
        # The default hotkey collides on every schema except rime_ice: they all
        # import the shared `key_bindings:/emacs_editing` preset, which binds
        # Control+e to `send: End, when: composing` well before this one in the
        # built list. It still toggles - librime gives the last binding loaded
        # for a key the higher priority, checked by driving a real librime
        # session against a built double_pinyin_flypy - so the append is enough
        # and nothing has to be removed first. Which is as well: librime has no
        # list-subtraction operator, and a `key_binder/bindings/-` key fails the
        # whole schema build rather than being ignored.
        lines.append("  switches/+:")
        lines.append(
            "    - { name: annotate, reset: 1, states: [ gloss off, gloss on ] }"
        )
        lines.append("  key_binder/bindings/+:")
        # Quoted through `_quote` like the dictionary path above, and for the
        # same reason: this is a string out of a text field. Interpolated raw, a
        # `"` in it produced `accept: "Control+""` and failed the build of every
        # selected Chinese schema.
        lines.append(
            f'    - {{ accept: {_quote(settings["annotateHotkey"])}, toggle: annotate,'
            " when: composing }"
        )
        lines.append(f"  annotate/chinese: {str(settings['annotateChinese']).lower()}")
        lines.append(f"  annotate/english: {str(settings['annotateEnglish']).lower()}")
        # The filter reads both of these from the schema in its init: there is
        # no other channel into a lua_filter, and a filter that cannot see its
        # settings falls back to no dictionary at all.
        lines.append(f"  annotate/dictionary: {_quote(dictionary_path)}")
        lines.append(
            f"  annotate/show_pinyin: {str(settings['annotateShowPinyin']).lower()}"
        )
    if len(lines) == before:
        return None
    return "\n".join(lines) + "\n"


# Setting, the value that asks for a patch, the schemas that have a component
# reading it, and what to say about the ones that do not.
_UNREACHABLE = (
    (
        "traditionalize", True, TRADITIONALIZE_SCHEMAS,
        "traditional output: {schemas} convert through their own simplification"
        " switch rather than a traditionalize filter, so the setting does not"
        " reach them",
    ),
)


def notices(settings: dict) -> list[str]:
    """What this configuration asked for and cannot deliver, in plain words.

    A setting that lands on some selected schemas and not others is the same
    silent half-application as a patch written to the wrong file - the user set
    it, the deploy succeeded, and only the typing tells them. So the schemas a
    setting cannot reach are named at deploy time.

    Only a setting that actually asks for a patch is reported: "traditional
    output is off and also would not have worked" is not news. The Japanese
    schemas are never named either - they are out of scope by design, not by
    accident, and reporting them every deploy would train the user to ignore
    the line that matters.
    """
    selected = [
        schema for schema in _schema_list(settings) if schema in ANNOTATED_SCHEMAS
    ]
    messages = []
    for key, asked, applicable, template in _UNREACHABLE:
        if settings[key] != asked:
            continue
        unreachable = [schema for schema in selected if schema not in applicable]
        if unreachable:
            messages.append(template.format(schemas=", ".join(unreachable)))
    return messages


def render(settings: dict, dictionary_path: str | None = None) -> dict[str, str]:
    """Return every Rime file this configuration needs, keyed by relative path.

    One `<schema_id>.custom.yaml` per selected schema that needs one, because
    that is the only file Rime reads for a schema. A schema that needs none is
    left out entirely rather than given an empty patch, and a schema that stops
    being selected simply stops being rendered - which is what lets the manifest
    delete its file on the next deploy.

    `dictionary_path` is where the annotation dictionary is cached. It is passed
    in rather than derived here so that rendering stays a function of its
    arguments alone - tests can render any configuration without a real cache or
    a real home directory. The default is where ime-manager would have put it.
    """
    if dictionary_path is None:
        dictionary_path = assets.default_dictionary_path()
    files = {"default.custom.yaml": _default_custom(settings)}
    for schema in _schema_list(settings):
        body = _schema_custom(settings, schema, str(dictionary_path))
        if body is not None:
            files[f"{schema}.custom.yaml"] = body
    return files


# Where classicui's configuration lives, relative to the Fcitx5 config
# directory. Fcitx5 writes it itself when the user opens its own settings, which
# is why the file is rendered whole here: a merge would have to guess which of
# the keys in it were the user's.
CLASSICUI_PATH = "conf/classicui.conf"

# The classicui keys this plugin holds an opinion about but no setting for. Font
# is the one that matters: a candidate window that falls back to a face without
# CJK glyphs draws boxes where the candidates should be. Each entry is
# (comment, key, value), and the comment is the one Fcitx5's own writer puts
# above that key.
#
# The named face has to be a face that is there. This wrote "HanaMinA" into
# every user's classicui.conf with a comment claiming it covered the CJK - and
# `fc-list | grep -i hanamin` matches nothing on an Omarchy machine, because
# nothing installs it: it is not in omarchy-base.packages and it was not in
# packages.REQUIRED either. Everybody was silently on whatever fontconfig
# substituted, which happened to work only because noto-fonts-cjk is an Omarchy
# base package. So the file now names that font, and packages.REQUIRED asks for
# it, which makes the claim in this comment one the plugin can back up.
CLASSICUI_FONT = "Noto Sans CJK SC Medium"
CLASSICUI_FIXED = (
    ("Use mouse wheel to go to prev or next page", "WheelForPaging", "True"),
    ("Font", "Font", f'"{CLASSICUI_FONT} 12"'),
    ("Menu Font", "MenuFont", f'"{CLASSICUI_FONT} 12"'),
    ("Tray Font", "TrayFont", f'"{CLASSICUI_FONT} 11"'),
    ("Tray Label Outline Color", "TrayOutlineColor", "#000000"),
    ("Tray Label Text Color", "TrayTextColor", "#ffffff"),
    ("Prefer Text Icon", "PreferTextIcon", "True"),
    ("Show Layout Name In Icon", "ShowLayoutNameInIcon", "True"),
    ("Use input method language to display text",
     "UseInputMethodLanguageToDisplayText", "True"),
    ("Follow system light/dark color scheme", "UseDarkTheme", "True"),
    ("Follow system accent color if it is supported by theme and desktop",
     "UseAccentColor", "True"),
    ("Use Per Screen DPI on X11", "PerScreenDPI", "True"),
    ("Force font DPI on Wayland", "ForceWaylandDPI", "0"),
    ("Enable fractional scale under Wayland", "EnableFractionalScale", "True"),
)


def _classicui(settings: dict, theme_directory: str) -> str:
    entries = [
        ("Vertical Candidate List", "Vertical Candidate List",
         "True" if settings["verticalCandidates"] else "False"),
        *CLASSICUI_FIXED,
        ("Theme", "Theme", theme_directory),
        ("Dark Theme", "DarkTheme", theme_directory),
    ]
    lines = [HEADER.rstrip("\n")]
    for comment, key, value in entries:
        lines.append(f"# {comment}")
        lines.append(f"{key}={value}")
    return "\n".join(lines) + "\n"


def render_fcitx5(settings: dict, theme_directory: str) -> dict[str, str]:
    """Return every Fcitx5 file this configuration needs, keyed by relative path.

    So far that is classicui.conf, and it is generated rather than shipped
    because of what shipping it cost. `verticalCandidates` wrote
    `style/horizontal` into Rime's own configuration and stopped there; under
    Fcitx5 the candidate layout belongs to classicui, whose key is
    `Vertical Candidate List` - and the shipped file pinned that to True. The
    switch was wired to a key with no reader, so turning it off did nothing and
    looked like a bug in Rime. The same class of mistake as the `englishInput`
    switch that was retired for the same reason.

    `theme_directory` is the generated theme's directory name, handed in rather
    than imported so this module keeps knowing only how to render settings, and
    lib/theme stays the one place that names the directory.
    """
    return {CLASSICUI_PATH: _classicui(settings, theme_directory)}


# --- the Fcitx5 profile -------------------------------------------------------
#
# The profile is the user's Fcitx5 identity: their keyboard layout, their input
# method groups, and every input method they have ever added. It used to ship as
# a payload file and be copied straight over the top, which pinned
# `Default Layout=us` and `keyboard-us` onto everybody and threw away whatever
# else they had configured. Omarchy derives Hyprland's `kb_layout` from the
# installer's XKBLAYOUT (see /usr/share/omarchy/default/hypr/input.lua), so a
# German install has `de` and this plugin was silently putting them back on a US
# keyboard every deploy.
#
# So it is merged rather than written. Rime is added to the group that is there
# and made its default input method; the layout, the group's name, and every
# other item stay exactly as the user left them.

PROFILE_PATH = "profile"

# The Fcitx5 input method this plugin exists to put in front of the user.
RIME_IM = "rime"

# What a machine with no XKBLAYOUT gets, which is also what xkb itself defaults
# to.
DEFAULT_LAYOUT = "us"

PROFILE_HEADER = (
    "# Merged by ryuhzk.ime: Rime is added to the group that was already here.\n"
    "# Your layout, your groups and your other input methods are left alone.\n"
)

_GROUP = "Groups/0"
_ITEM = re.compile(r"^Groups/0/Items/(\d+)$")


def system_layout(vconsole=Path("/etc/vconsole.conf")) -> str:
    """The keyboard layout this system was installed with.

    Read from the same place Omarchy reads it, so a profile written from
    scratch agrees with the compositor instead of assuming a US keyboard. Only
    the first layout of a list is taken: a Fcitx5 group carries one.
    """
    try:
        text = Path(vconsole).read_text(encoding="utf-8", errors="replace")
    except OSError:
        return DEFAULT_LAYOUT
    for line in text.splitlines():
        key, separator, value = line.strip().partition("=")
        if not separator or key.strip() != "XKBLAYOUT":
            continue
        value = value.split("#")[0].strip().strip('"').strip("'")
        first = value.split(",")[0].strip()
        if first:
            return first
    return DEFAULT_LAYOUT


def _profile_parser() -> configparser.RawConfigParser:
    """A parser that leaves Fcitx5's keys alone.

    `Default Layout` has a space in it and `DefaultIM` has capitals in it;
    configparser lowercases option names unless it is told not to, and a
    profile whose keys have been renamed is a profile Fcitx5 ignores.
    """
    parser = configparser.RawConfigParser()
    parser.optionxform = str
    return parser


def _fresh_profile(layout: str) -> configparser.RawConfigParser:
    parser = _profile_parser()
    parser[_GROUP] = {
        "Name": "Default",
        "Default Layout": layout,
        "DefaultIM": RIME_IM,
    }
    parser[f"{_GROUP}/Items/0"] = {"Name": f"keyboard-{layout}", "Layout": ""}
    parser[f"{_GROUP}/Items/1"] = {"Name": RIME_IM, "Layout": ""}
    parser["GroupOrder"] = {"0": "Default"}
    return parser


def render_profile(existing: str | None = None, layout: str | None = None) -> str:
    """Return the Fcitx5 profile with Rime added to whatever was already there.

    `existing` is the profile currently on disk, or None when there is none.
    `layout` is only used when a profile has to be written from scratch; it
    defaults to what the system says.

    A profile that cannot be parsed is treated as no profile at all: the file
    is backed up before it is replaced, so the user's own copy is recoverable,
    and refusing to deploy over a corrupt one would leave them with no input
    method instead.
    """
    if layout is None:
        layout = system_layout()

    parser = _profile_parser()
    if existing:
        try:
            parser.read_string(existing)
        except configparser.Error:
            parser = _profile_parser()

    if not parser.has_section(_GROUP):
        parser = _fresh_profile(layout)
    else:
        items = sorted(
            (int(_ITEM.match(section).group(1)), section)
            for section in parser.sections()
            if _ITEM.match(section)
        )
        names = [parser[section].get("Name", "") for _, section in items]
        if RIME_IM not in names:
            # Appended rather than inserted: the order of a group's items is
            # the order Fcitx5 enumerates them in, and the user chose it.
            parser[f"{_GROUP}/Items/{len(items)}"] = {"Name": RIME_IM, "Layout": ""}
        parser[_GROUP]["DefaultIM"] = RIME_IM
        if not parser[_GROUP].get("Default Layout"):
            parser[_GROUP]["Default Layout"] = layout

    buffer = io.StringIO()
    _ordered(parser).write(buffer, space_around_delimiters=False)
    return PROFILE_HEADER + buffer.getvalue().strip() + "\n"


def _section_key(name: str):
    """Sort `Groups/0/Items/10` after `Groups/0/Items/2`, and groups first.

    configparser appends a new section at the end, so an added Rime item came
    out below `[GroupOrder]`. Fcitx5's reader does not care, but a profile a
    person may open should read in the order they wrote it.
    """
    parts = []
    for part in name.split("/"):
        parts.append((0, int(part), "") if part.isdigit() else (1, 0, part))
    return (0 if name.startswith("Groups/") else 1, parts)


def _ordered(parser: configparser.RawConfigParser) -> configparser.RawConfigParser:
    ordered = _profile_parser()
    for section in sorted(parser.sections(), key=_section_key):
        ordered[section] = dict(parser[section])
    return ordered


# --- the environment override ------------------------------------------------
#
# Omarchy ships /usr/lib/environment.d/10-omarchy-fcitx.conf. systemd reads
# ~/.config/environment.d after it, and a file with the same name there replaces
# the packaged one entirely - which is the whole mechanism, and also the whole
# hazard: every variable the packaged file carries and this one does not is a
# variable the user silently loses. So the file is generated from the packaged
# one rather than written out from a list here, and only the variable that has
# to go is removed.

# The name both files share. Anything else and systemd would apply both.
ENVIRONMENT_PATH = "10-omarchy-fcitx.conf"

PACKAGED_ENVIRONMENT = Path("/usr/lib/environment.d") / ENVIRONMENT_PATH

# What the packaged file said when this was diagnosed. It is only reached when
# the packaged file cannot be read at all - a machine where Omarchy has not
# installed it, or a test - because a generated file with no variables in it
# would take the input method down rather than leave it as it was.
ENVIRONMENT_FALLBACK = (
    "INPUT_METHOD=fcitx",
    "QT_IM_MODULE=fcitx",
    "XMODIFIERS=@im=fcitx",
    "SDL_IM_MODULE=fcitx",
)

# The one variable this file exists to remove. See the header below.
DROPPED_ENVIRONMENT = ("QT_IM_MODULE",)

_ASSIGNMENT = re.compile(r"^([A-Za-z_][A-Za-z0-9_]*)=(.*)$")

ENVIRONMENT_HEADER = """\
# This file is generated by ryuhzk.ime. Edits are lost on the next deploy.
# `ime-manager uninstall` removes it, and the packaged file applies again.
#
# It overrides /usr/lib/environment.d/10-omarchy-fcitx.conf by carrying that
# file's own name in a directory systemd reads later. Nothing here reaches a
# session that is already running: it takes effect at your next login.
#
# Every variable below is copied from the packaged file unchanged. The one
# difference is that QT_IM_MODULE is deliberately not set. fcitx5 prints this
# in its own self-diagnosis:
#
#   Using Wayland native input method protocol: 1
#   GTK_IM_MODULE=
#   QT_IM_MODULE=fcitx
#
# The native protocol (text-input-v3) is up and GTK already uses it, but
# QT_IM_MODULE=fcitx forces Qt down the older DBus input-context path instead.
# With both routes live, a layer-shell surface such as an Omarchy panel gets
# whichever one wins the focus race, which is why typing Chinese into one
# worked only sometimes. Leaving QT_IM_MODULE unset puts Qt on the same native
# protocol as GTK.
#
# The rest stay for reasons of their own: XMODIFIERS is what XWayland and
# Qt-on-xcb fall back to, and SDL_IM_MODULE and INPUT_METHOD have no
# Wayland-native equivalent to be crowded out by.
"""


def packaged_environment(path=None) -> list[str]:
    """The `NAME=VALUE` lines of the packaged file, in order.

    Comments and blank lines are dropped rather than copied: the packaged file's
    own commentary describes the packaged file, and this one carries its own.
    An unreadable file falls back to what the packaged file held when the
    QT_IM_MODULE diagnosis was made.
    """
    if path is None:
        path = PACKAGED_ENVIRONMENT
    try:
        text = Path(path).read_text(encoding="utf-8", errors="replace")
    except OSError:
        text = "\n".join(ENVIRONMENT_FALLBACK)
    return [line.strip() for line in text.splitlines()
            if _ASSIGNMENT.fullmatch(line.strip())]


def render_environment(packaged=None) -> dict[str, str]:
    """Return the environment override, keyed by its relative path.

    `packaged` is where the packaged file lives; it is an argument so that
    rendering stays a function of what it is handed, and so no test reads
    /usr/lib.
    """
    lines = [ENVIRONMENT_HEADER.rstrip("\n")]
    for line in packaged_environment(packaged):
        name = _ASSIGNMENT.fullmatch(line).group(1)
        if name in DROPPED_ENVIRONMENT:
            continue
        lines.append(line)
    return {ENVIRONMENT_PATH: "\n".join(lines) + "\n"}
