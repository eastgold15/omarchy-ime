"""Every feature the plugin can install beyond the core, declared once each.

The core is Fcitx5, Rime Ice, the panel, the candidate window's theme and the
deploy transaction. A feature is something a user can have or not have: today
candidate annotation, switched on by the `annotation` setting, and Japanese
input, switched on by selecting one of its schemas. Each is one `Feature`
record here, and every module that acts on a feature reads that record instead
of keeping a table of its own: lib/deploy.py asks it which payload groups to
install and which pinned sources to fetch, lib/generate.py asks it what to
write into a schema's customization file, and ime-manager asks it where a
feature's schema yaml lives before it is deployed. The tables those modules
used to keep - `GROUP_SCHEMAS`, `SCHEMA_SOURCES`, `ANNOTATED_SCHEMAS` - are
either gone or derived from the records below, and tests/test_features.py
refuses a second copy of any fact a record already states.

Adding a feature is adding one record with these fields, and nothing in
deploy, generate or assets changes. The planned LLM sentence translation
(docs/TODO.md) will be:

    TRANSLATION = Feature(
        id="translation",
        setting="translation",          # its off switch; default false
        schemas=(),                     # it brings no schema of its own
        groups=("rime-translation",),   # payload/rime-translation/lua/...
        sources={},                     # nothing pinned to fetch
        dictionary=False,               # it does not read CC-CEDICT
        settings=("translation", "translationEndpoint", "translationModel",
                  "translationLanguage", "translationHotkey"),
        patched=frozenset(settings_lib.SCHEMA_IDS),  # every deployed schema,
                                        # so the injected key never leaks
        patch=_translation_patch,       # its filter and `when: always` binding
    )

added to FEATURES, with its settings declared in lib/settings.DEFAULTS and
manifest.json, its payload directory mapped to a target in
lib/deploy.PAYLOAD_GROUPS, and its rows in the panel. That is the whole list.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Callable, Mapping

from lib import dicts
from lib import settings as settings_lib


@dataclass(frozen=True)
class PatchContext:
    """What a patch renderer is handed besides the settings.

    `dictionary_path` is where the annotation dictionary is cached, resolved by
    the caller so rendering stays a function of its arguments. `quote` is
    lib/generate's YAML double-quoting: every value that came out of a text
    field goes through it, so a `"` or a newline someone typed is data in the
    generated file and never syntax. It is handed over rather than imported
    because lib/generate imports this module, and because the rule for what a
    safe YAML scalar looks like belongs to the module that writes YAML.
    """

    dictionary_path: str
    quote: Callable[[str], str]


@dataclass(frozen=True)
class Feature:
    """One feature, and everything a deploy needs to know about it.

    `setting` is the boolean setting that switches the feature on, or None
    when it is switched on by selecting one of its `schemas`. A feature with
    neither is always on.

    `groups` are the payload directories installed while the feature is
    enabled, and removed by the ordinary stale-file sweep once it is not; each
    has its target in lib/deploy.PAYLOAD_GROUPS.

    `sources` maps each of the feature's schemas to the pinned sources
    (lib/assets.SOURCES) whose tables that schema imports. Per schema rather
    than per feature because the two Japanese schemas do not need the same
    ones, and a source is fetched only while a schema that names it is
    selected - so a user who never picks a Japanese schema never touches the
    network. A schema whose sources cannot be fetched is withheld from the
    deploy, which is why the mapping has to be exact: it was checked against
    what each schema actually reads.

    `dictionary` says whether the feature reads the CC-CEDICT download, which
    is an asset of a different kind from the pinned sources - unpinnable,
    refreshed in place, and read from the cache rather than copied into the
    Rime directory - and is fetched only while a feature that reads it is
    active.

    `settings` are the keys in lib/settings.DEFAULTS the feature owns.

    `patched` are the schemas whose `<schema>.custom.yaml` carries this
    feature's patch, and `patch` renders it: the lines to append under
    `patch:`, or an empty list. It is a callable rather than a declarative
    structure because every value it writes depends on the settings, one of
    them is a flow-style mapping with a user-typed string inside, and the
    generated bytes are pinned by a fixture; a structure would need a YAML
    emitter that reproduces those bytes exactly, which is a second thing to get
    wrong for one consumer. lib/generate keeps the file's shape - the header,
    the `patch:` line, a file omitted rather than blanked when nothing applies
    - and the quoting rule; the feature keeps what its patch says.

    `wanted` is an optional narrowing of "enabled": the feature is *active*
    when it is enabled and, if `wanted` is given, `wanted(settings)` holds.
    Payload groups follow enabled; the patch and the dictionary follow active.
    Annotation is the case: with the master switch on and both gloss
    directions off, the filter file is installed but nothing asks for it.
    """

    id: str
    setting: str | None
    schemas: tuple[str, ...]
    groups: tuple[str, ...]
    sources: Mapping[str, tuple[str, ...]]
    dictionary: bool
    settings: tuple[str, ...]
    patched: frozenset[str]
    patch: Callable[[dict, str, PatchContext], list[str]] | None
    wanted: Callable[[dict], bool] | None = None

    def enabled(self, settings: dict) -> bool:
        """Whether this configuration installs the feature.

        The selection is read through lib/settings.schema_selection so that a
        hand-edited list is repaired here the same way the deploy and the
        renderer repair it: a feature that read the raw list would install a
        group for a schema that never reaches schema_list.
        """
        if self.setting is not None:
            return bool(settings[self.setting])
        if self.schemas:
            selected = settings_lib.schema_selection(settings.get("schemas"))
            return any(schema in selected for schema in self.schemas)
        return True

    def active(self, settings: dict) -> bool:
        """Whether the feature has work to do: its patch, its dictionary."""
        return self.enabled(settings) and (self.wanted is None or self.wanted(settings))


# --- candidate annotation ----------------------------------------------------


def _glossing(settings: dict) -> bool:
    """Whether at least one gloss direction is on."""
    return bool(settings["annotateChinese"] or settings["annotateEnglish"])


def _annotation_patch(settings: dict, schema: str, context: PatchContext) -> list[str]:
    """The annotation filter, its switch, its hotkey and its settings.

    One switch, not one per direction. Rime's key_binder applies the first
    binding that matches and stops, so two bindings on the same key would
    leave the second one dead - and dead in the quiet way, where the key
    appears to work because the other direction still toggles.

    The split that does work: the hotkey answers "show glosses right now",
    which is worth reaching for mid-word, and which direction to gloss is a
    setting, because nobody changes their mind about that while typing.

    The default hotkey collides on every schema except rime_ice: they all
    import the shared `key_bindings:/emacs_editing` preset, which binds
    Control+e to `send: End, when: composing` well before this one in the
    built list. It still toggles - librime gives the last binding loaded for a
    key the higher priority, checked by driving a real librime session against
    a built double_pinyin_flypy - so the append is enough and nothing has to
    be removed first. Which is as well: librime has no list-subtraction
    operator, and a `key_binder/bindings/-` key fails the whole schema build
    rather than being ignored.

    The hotkey and the dictionary path both go through `context.quote`: each
    is a string out of a text field. Interpolated raw, a `"` in the hotkey
    produced `accept: "Control+""` and failed the build of every selected
    Chinese schema.

    The filter reads `annotate/*` from the schema in its init: there is no
    other channel into a lua_filter, and a filter that cannot see its settings
    falls back to no dictionary at all.
    """
    quote = context.quote
    return [
        '  "engine/filters/+":',
        '    - "lua_filter@*annotate"',
        "  switches/+:",
        "    - { name: annotate, reset: 1, states: [ gloss off, gloss on ] }",
        "  key_binder/bindings/+:",
        f'    - {{ accept: {quote(settings["annotateHotkey"])}, toggle: annotate,'
        " when: composing }",
        f"  annotate/chinese: {str(settings['annotateChinese']).lower()}",
        f"  annotate/english: {str(settings['annotateEnglish']).lower()}",
        f"  annotate/dictionary: {quote(context.dictionary_path)}",
        f"  annotate/show_pinyin: {str(settings['annotateShowPinyin']).lower()}",
    ]


# The annotation patch is written for every Chinese schema in the catalogue,
# because every one of them composes Chinese and a Chinese-English gloss on a
# Chinese candidate is a gloss of that candidate. Rime reads
# `<schema_id>.custom.yaml` and nothing else, so it has to reach one file per
# selected schema.
#
# The Japanese two are not here, and that is a decision rather than an
# omission. Their candidates are Japanese, and a CC-CEDICT entry for a kanji
# string is the Chinese word that shares its characters, not a translation of
# the Japanese one. Both schemas also already fill the candidate comment
# themselves - japanese_tw_eng with `simplifier@jpzh_translate_suggestion`
# (`show_in_comment: true`) and its reverse-lookup filters, sno_japanese with
# the romaji reading - so the filter would be fighting over the one slot it
# writes to.
ANNOTATION = Feature(
    id="annotation",
    setting="annotation",
    schemas=(),
    # payload/rime holds the filter and nothing else. The directory keeps its
    # original name because three documents and the security review name it.
    groups=("rime",),
    sources={},
    dictionary=True,
    settings=("annotation", "annotateChinese", "annotateEnglish",
              "annotateShowPinyin", "annotateHotkey"),
    patched=frozenset(settings_lib.CHINESE_SCHEMAS),
    patch=_annotation_patch,
    wanted=_glossing,
)


# --- Japanese input ----------------------------------------------------------
#
# Two schemas, in the order lib/generate places them around the Chinese ones:
# the mixed schema first, because it is the one reached by default, and the
# Japanese-only schema last. Their schema files ship in payload/rime-japanese;
# their dictionaries are fetched from two repositories pinned by commit.
#
# sno_japanese composes from the `japanese` dictionary alone, which is built
# from rime-japanese's mozc, jmdict and kana tables. japanese_tw_eng also
# reverse-looks-up through japanese_pinyin and translate_en2jp, whose tables
# come from rime-snomiao, so it needs both.
JAPANESE = Feature(
    id="japanese",
    setting=None,
    schemas=("japanese_tw_eng", "sno_japanese"),
    groups=("rime-japanese",),
    sources={
        "japanese_tw_eng": ("rime-japanese", "rime-snomiao"),
        "sno_japanese": ("rime-japanese",),
    },
    dictionary=False,
    settings=(),
    patched=frozenset(),
    patch=None,
)


# --- cell dictionaries -------------------------------------------------------
#
# Switched on by a non-empty `dictionaries` list rather than a boolean - the
# list itself is the switch. The patch is one line: the schema's translator
# stops naming its base table and names the generated wrapper that imports the
# base plus the selected cells (lib/dicts renders the wrapper). The wrapper
# files are generated, and the cell tables themselves arrive through the
# rime-frost source; both halves are handled in lib/deploy, which also strips
# the selection for a deploy whose fetch failed, so an unreachable upstream
# means "no cells this time" rather than an unbuildable schema.
def _cells_patch(settings: dict, schema: str, context: PatchContext) -> list[str]:
    return [f"  translator/dictionary: {dicts.wrapper_name(schema)}"]


CELLS = Feature(
    id="cells",
    setting="dictionaries",
    schemas=(),
    groups=(),
    # Not declared per schema: the source is needed while any cell is selected,
    # whatever schemas are. lib/deploy.needed_sources reads it from lib/dicts.
    sources={},
    dictionary=False,
    settings=("dictionaries",),
    patched=frozenset(dicts.CELL_SCHEMAS),
    patch=_cells_patch,
)


FEATURES = (ANNOTATION, JAPANESE, CELLS)


# --- the views the other modules read ----------------------------------------

# Schema -> the pinned sources its tables come from, across every feature.
SCHEMA_SOURCES: dict[str, tuple[str, ...]] = {
    schema: sources
    for feature in FEATURES
    for schema, sources in feature.sources.items()
}


def owner(group: str) -> Feature | None:
    """The feature a payload group belongs to, or None for a core group."""
    for feature in FEATURES:
        if group in feature.groups:
            return feature
    return None


def dictionary_wanted(settings: dict) -> bool:
    """Whether any active feature reads the CC-CEDICT dictionary."""
    return any(feature.dictionary and feature.active(settings) for feature in FEATURES)


def patches(settings: dict, schema: str, context: PatchContext) -> list[str]:
    """Every active feature's patch lines for one schema, in feature order."""
    lines: list[str] = []
    for feature in FEATURES:
        if feature.patch is None or schema not in feature.patched:
            continue
        if feature.active(settings):
            lines.extend(feature.patch(settings, schema, context))
    return lines
